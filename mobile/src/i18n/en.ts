type Plural = { one: string; other: string };
type DeepString<T> = T extends string ? string : T extends Plural ? Plural : { [K in keyof T]: DeepString<T[K]> };

export type Dict = DeepString<typeof en>;

type Keys<T, P extends string = ''> = {
  [K in keyof T & string]: T[K] extends string | Plural ? `${P}${K}` : Keys<T[K], `${P}${K}.`>;
}[keyof T & string];

export type TKey = Keys<typeof en>;

export default en as Dict;
